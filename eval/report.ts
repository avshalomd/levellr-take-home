// eval/results/report.md, generated from eval/results/*.json so the numbers written in the README can be pasted from
// what was measured, never typed by hand. Either result file may be missing; its section then says so.
// Ported in shape from Community Pulse 90f193d (eval/report.ts).
// usage: npm run eval:report
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const load = (p: string) => (existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null);
const a = load("eval/results/agent.json");
const r = load("eval/results/retrieval.json");
const pct = (x: number | null | undefined) => (x == null ? "–" : `${Math.round(x * 100)}%`);

type Arm = { precision_at_8: number; recall_at_8: number; ndcg_at_8: number; gold_hit_rate: number | null; gold_mrr: number | null; median_ms: number };
type Run = { id: string; type: string; question: string; judge?: { verdict: string; reason: string }; error?: string };

const retrieval = r
  ? `## Retrieval arms (${r.run_at.slice(0, 16).replace("T", " ")} UTC, ${r.questions} lookup questions, top ${r.k})

Relevance is pooled across the six arms and judged once per conversation by ${r.judge}, blind to the arm. Recall is
against every relevant conversation any arm found. "Gold found" = a conversation holding a hand-picked gold message is
in the top ${r.k}.

| arm | precision@8 | recall@8 | nDCG@8 | gold found | MRR | median time |
|---|---|---|---|---|---|---|
${Object.entries(r.summary as Record<string, Arm>)
  .map(
    ([k, m]) =>
      `| ${k} | ${pct(m.precision_at_8)} | ${pct(m.recall_at_8)} | ${m.ndcg_at_8.toFixed(2)} | ${pct(m.gold_hit_rate)} | ${m.gold_mrr?.toFixed(2) ?? "–"} | ${(m.median_ms / 1000).toFixed(1)} s |`,
  )
  .join("\n")}
`
  : "## Retrieval arms\n\nNot run yet: `npm run eval:retrieval`.\n";

const s = a?.summary;
const agent = a
  ? `## End to end (${a.run_at.slice(0, 16).replace("T", " ")} UTC, agent ${a.agent_model}, judge ${a.judge})

| | |
|---|---|
| answer score (correct = 1, partial = ½) | **${pct(s.score)}** (${s.correct} correct, ${s.partial} partial, ${s.wrong} wrong, ${s.errors} errors, of ${s.questions}) |
| by kind | ${Object.entries(s.by_type as Record<string, { n: number; score: number | null }>).map(([t, v]) => `${t} ${pct(v.score)} (n=${v.n})`).join(" · ")} |
| cited claims supported by their source (Jev) | **${pct(s.citations.supported_share)}** (${s.citations.supported}/${s.citations.cited - s.citations.unchecked}) |
| made-up citation ids / cited but never read this turn | ${s.citations.invalid} / ${s.citations.not_retrieved} of ${s.citations.total} citations |
| declined or corrected when it should | ${s.abstained_when_it_should} |
| declined when it should not | ${s.abstained_when_it_should_not} |
| answers with invented facts (judge) | ${s.invented} |
| latency | p50 ${Math.round(s.latency_ms.p50 / 1000)} s, p90 ${Math.round(s.latency_ms.p90 / 1000)} s |

### Every answer that was not fully correct

| id | question | verdict | judge's reason |
|---|---|---|---|
${(a.runs as Run[])
  .filter((x) => x.judge?.verdict !== "correct")
  .map((m) => `| ${m.id} | ${m.question} | ${m.judge?.verdict ?? "error"} | ${(m.judge?.reason ?? m.error ?? "").replace(/\|/g, "/").replace(/\n/g, " ")} |`)
  .join("\n")}
`
  : "## End to end\n\nNot run yet: `npm run eval:agent` (spends the agent model's quota).\n";

writeFileSync("eval/results/report.md", `# Eval results\n\nGenerated by \`eval/report.ts\`.\n\n${retrieval}\n${agent}`);
console.log("wrote eval/results/report.md");
